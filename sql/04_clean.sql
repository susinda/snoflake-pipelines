USE WAREHOUSE STUDENT_WH;

-- 1. Create CLEAN tables
CREATE TABLE IF NOT EXISTS STUDENT.CLEAN.ENROLMENTS (
    ENROLMENT_ID NUMBER(10,0),
    STUDENT_ID VARCHAR(20),
    COURSE_CODE VARCHAR(20),
    ENROLMENT_DATE DATE,
    STATUS VARCHAR(20),
    TUITION_FEE NUMBER(10,2),
    UPDATED_AT TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS STUDENT.CLEAN.STUDENT_PAYMENTS (
    PAYMENT_ID VARCHAR(20),
    ENROLMENT_ID NUMBER(10,0),
    PAYMENT_DATE DATE,
    AMOUNT NUMBER(10,2),
    PAYMENT_STATUS VARCHAR(20),
    UPDATED_AT TIMESTAMP_NTZ
);

-- 2. Track RAW changes
CREATE STREAM IF NOT EXISTS STUDENT.RAW.ENROLMENTS_STREAM
    ON TABLE STUDENT.RAW.ENROLMENTS
    SHOW_INITIAL_ROWS = TRUE;

CREATE STREAM IF NOT EXISTS STUDENT.RAW.PAYMENTS_STREAM
    ON TABLE STUDENT.RAW.STUDENT_PAYMENTS
    SHOW_INITIAL_ROWS = TRUE;

-- 3. Create executable cleaning procedure
CREATE OR REPLACE PROCEDURE STUDENT.CLEAN.REFRESH_CLEAN()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
BEGIN

    BEGIN TRANSACTION;

    -- Clean enrolments and upsert by enrolment ID
    MERGE INTO STUDENT.CLEAN.ENROLMENTS tgt
    USING (
        SELECT
            ENROLMENT_ID,
            TRIM(STUDENT_ID) AS STUDENT_ID,
            UPPER(TRIM(COURSE_CODE)) AS COURSE_CODE,
            ENROLMENT_DATE,
            UPPER(TRIM(STATUS)) AS STATUS,
            TUITION_FEE,
            UPDATED_AT
        FROM STUDENT.RAW.ENROLMENTS_STREAM
        WHERE METADATA$ACTION = 'INSERT'
          AND ENROLMENT_ID IS NOT NULL
          AND NULLIF(TRIM(STUDENT_ID), '') IS NOT NULL
          AND TUITION_FEE >= 0
        QUALIFY ROW_NUMBER() OVER (
            PARTITION BY ENROLMENT_ID
            ORDER BY UPDATED_AT DESC NULLS LAST
        ) = 1
    ) src
    ON tgt.ENROLMENT_ID = src.ENROLMENT_ID

    WHEN MATCHED AND (
        tgt.UPDATED_AT IS NULL
        OR src.UPDATED_AT >= tgt.UPDATED_AT
    ) THEN UPDATE SET
        tgt.STUDENT_ID = src.STUDENT_ID,
        tgt.COURSE_CODE = src.COURSE_CODE,
        tgt.ENROLMENT_DATE = src.ENROLMENT_DATE,
        tgt.STATUS = src.STATUS,
        tgt.TUITION_FEE = src.TUITION_FEE,
        tgt.UPDATED_AT = src.UPDATED_AT

    WHEN NOT MATCHED THEN INSERT (
        ENROLMENT_ID, STUDENT_ID, COURSE_CODE,
        ENROLMENT_DATE, STATUS, TUITION_FEE, UPDATED_AT
    )
    VALUES (
        src.ENROLMENT_ID, src.STUDENT_ID, src.COURSE_CODE,
        src.ENROLMENT_DATE, src.STATUS,
        src.TUITION_FEE, src.UPDATED_AT
    );

    -- Clean payments and upsert by payment ID
    MERGE INTO STUDENT.CLEAN.STUDENT_PAYMENTS tgt
    USING (
        SELECT
            TRIM(PAYMENT_ID) AS PAYMENT_ID,
            ENROLMENT_ID,
            PAYMENT_DATE,
            AMOUNT,
            UPPER(TRIM(PAYMENT_STATUS)) AS PAYMENT_STATUS,
            UPDATED_AT
        FROM STUDENT.RAW.PAYMENTS_STREAM
        WHERE METADATA$ACTION = 'INSERT'
          AND NULLIF(TRIM(PAYMENT_ID), '') IS NOT NULL
          AND ENROLMENT_ID IS NOT NULL
          AND AMOUNT >= 0
        QUALIFY ROW_NUMBER() OVER (
            PARTITION BY TRIM(PAYMENT_ID)
            ORDER BY UPDATED_AT DESC NULLS LAST
        ) = 1
    ) src
    ON tgt.PAYMENT_ID = src.PAYMENT_ID

    WHEN MATCHED AND (
        tgt.UPDATED_AT IS NULL
        OR src.UPDATED_AT >= tgt.UPDATED_AT
    ) THEN UPDATE SET
        tgt.ENROLMENT_ID = src.ENROLMENT_ID,
        tgt.PAYMENT_DATE = src.PAYMENT_DATE,
        tgt.AMOUNT = src.AMOUNT,
        tgt.PAYMENT_STATUS = src.PAYMENT_STATUS,
        tgt.UPDATED_AT = src.UPDATED_AT

    WHEN NOT MATCHED THEN INSERT (
        PAYMENT_ID, ENROLMENT_ID, PAYMENT_DATE,
        AMOUNT, PAYMENT_STATUS, UPDATED_AT
    )
    VALUES (
        src.PAYMENT_ID, src.ENROLMENT_ID,
        src.PAYMENT_DATE, src.AMOUNT,
        src.PAYMENT_STATUS, src.UPDATED_AT
    );

    COMMIT;

    RETURN 'CLEAN layer refreshed successfully';

EXCEPTION
    WHEN OTHER THEN
        ROLLBACK;
        RAISE;
END;
$$;
